-- 쓰기의 대가: updated_at 은 값이 바뀐 모든 쓰기가 옮기는 칸이라 이 인덱스가 HOT 갱신을 막는다. 측정에서는 인덱스가
-- 없어도 스캔 모양의 갱신 5만 건이 HOT 0 건이었다(채운 직후 · fillfactor 100 — 페이지에 자리가 없다). 자리가 생기는
-- 운영의 모양에서 잃는 몫은 재지 않았다(근거: 추정). 7-4 peak-day 가 쓰기 경로를 잴 때 함께 본다.
