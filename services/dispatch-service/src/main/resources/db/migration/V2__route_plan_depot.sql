-- =============================================================================
-- route_plans 에 캠프 좌표를 저장한다 (DESIGN.md §5.3, §6.2).
--
-- 좌표는 wave.closed 의 depot 스냅샷으로 들어온다(불변규칙 4 — 코어 서비스 간 동기 호출 금지).
-- 그런데 계획은 그 이벤트가 없는 자리에서도 다시 돌아야 한다:
--
--   * PLANNING 정체 회수 (§5.3) — 죽은 인스턴스가 남긴 계획을 스케줄러가 다시 돌린다
--   * 운영자 재실행 (§5.3 POST /plans/{waveId}/run)
--   * 부분 재계획 (§6.8) — delivery.at-risk 나 운영자 커맨드가 트리거다
--
-- 셋 다 wave.closed 를 다시 받지 않는다. 좌표를 계획 행에 남기지 않으면 그때 출발 지점을 알 수
-- 없고, 그것은 "라우트를 만들 수 없다" 와 같은 말이다.
--
-- V1 은 이미 main 에 있으므로 고치지 않는다 (불변규칙 13, 예외 없음).
-- =============================================================================

ALTER TABLE route_plans
  ADD COLUMN depot_lat NUMERIC(9,6),          -- 불변규칙 9
  ADD COLUMN depot_lng NUMERIC(9,6);

COMMENT ON COLUMN route_plans.depot_lat IS
  'wave.closed 의 depot 스냅샷. 재실행·정체 회수·부분 재계획은 그 이벤트를 다시 받지 않는다.';

-- NOT NULL 로 걸지 않는다. 이 컬럼이 생기기 전의 행이 있을 수 있고(로컬 개발 볼륨),
-- 값이 없는 계획은 재실행할 수 없다는 사실을 코드가 사유와 함께 말하는 편이
-- 마이그레이션이 기동을 막는 것보다 낫다. 새로 만드는 계획은 항상 값을 갖는다.
