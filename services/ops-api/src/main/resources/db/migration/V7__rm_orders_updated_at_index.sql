-- rm_routes · rm_waves (updated_at) 는 넣지 않는다 — 90일치 11만 행 · 3,640 행에서 순차 스캔 + 기존
-- ix_rmo_route · ix_rmo_wave 반조인이 3.8–9.7 ms · 0.2–0.4 ms 다. 재검토 지점: rm_routes 가 100만 행을 넘을 때.
