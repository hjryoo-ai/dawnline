package com.dawnline.messaging.outbox;

/**
 * 릴레이의 단일 활성 인스턴스를 정한다 (DESIGN.md §4.4, [ADR-027]).
 *
 * <h2>무엇을 지키는가</h2>
 * {@code FOR UPDATE SKIP LOCKED} 는 두 인스턴스가 <em>같은 행</em>을 발행하는 것을 막는다. 막지
 * 못하는 것은 <strong>키 단위 순서</strong>다 — 같은 {@code partition_key} 의 두 행이 서로 다른
 * 인스턴스에서 나가면 배치 시점과 전송 시점이 달라 §4.5 의 보장이 깨진다. 그 순서를 지키는 유일한
 * 방법은 어느 한 순간에 발행하는 인스턴스가 하나인 것이고, 그것을 정하는 것이 이 포트다.
 *
 * <h2>세 번째 상태를 값으로 둔다</h2>
 * "내가 리더다" 와 "남이 리더다" 만으로는 <strong>모른다</strong>를 표현할 수 없다. 조정자에
 * 닿지 못하면 판정 자체가 불가능한데, 그것을 {@code false} 로 접으면 운영자는 대시보드에서
 * "다른 인스턴스가 리더" 와 "아무도 판정하지 못하는 중" 을 구별할 수 없다. 발행을 멈추는
 * <em>결정</em>은 둘이 같지만 <em>봐야 할 곳</em>이 전혀 다르다 — 전자는 정상, 후자는 장애다.
 *
 * <h2>조정자는 outbox 가 있는 그 DB 다</h2>
 * 구현은 {@code AdvisoryLockRelayLeadership} 하나다(ADR-027 후속 정정 2026-09-05). 이 포트를
 * 남겨 두는 이유는 조정자를 바꿀 수 있게 하려는 것이 아니라, {@code OutboxRelay} 가 "발행해도
 * 되는가" 라는 <em>질문</em>에만 의존하고 그 답이 어디서 오는지 모르게 하기 위해서다 —
 * 테스트가 세 상태를 직접 만들어 넣을 수 있는 것도 그래서다.
 */
public interface RelayLeadership {

    /**
     * 지금 리더인가 — 아니면 되어 보고 답한다. 릴레이가 배치를 발행하기 <strong>전에</strong>
     * 매번 부른다.
     *
     * <p>"확인" 과 "획득" 이 한 메서드인 이유: 둘은 같은 질문의 두 경우이고, 나누면 호출부가
     * "지금 내가 리더인가" 를 상태로 들고 있어야 한다. <strong>그 상태가 실제 락과 어긋나는
     * 창이 곧 §4.5 가 깨지는 창이다.</strong>
     */
    State lead();

    /**
     * 리더십을 내려놓는다 (정상 종료). 다음 인스턴스가 바로 이어받게 한다.
     *
     * <p>실패해도 예외를 던지지 않는다 — 세션이 끊기면 어차피 서버가 락을 풀고, 종료 경로에서
     * 던진 예외는 종료를 실패로 보이게 만든다.
     */
    void stepDown();

    /**
     * 릴레이 리더십 상태.
     */
    enum State {

        /** 이 인스턴스가 리더다. 발행한다. */
        LEADER,

        /** 다른 인스턴스가 리더다. 발행하지 않는다. <strong>정상</strong>이다. */
        FOLLOWER,

        /**
         * 판정할 수 없다(DB 세션 장애). 발행하지 않는다. <strong>장애</strong>다.
         *
         * <p>조정자가 outbox 와 같은 DB 이므로, 이 상태에서는 발행할 행도 읽지 못한다. 그래서
         * "멈출 것인가 진행할 것인가" 라는 질문이 성립하지 않는다 — 진행할 방법이 없다.
         */
        UNKNOWN
    }
}
